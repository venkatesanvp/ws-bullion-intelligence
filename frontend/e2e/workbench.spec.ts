import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('synthetic listing → qualification → import → persisted history → watchlist', async ({ page, request }) => {
  const token = process.env.TEST_APP_TOKEN;
  if (!process.env.TEST_DATABASE_URL || !token) throw new Error('TEST_DATABASE_URL and TEST_APP_TOKEN must be configured; no production fallback.');
  const auth = { Authorization: 'Bearer ' + token, Origin: 'http://127.0.0.1:5173' };
  const root = 'http://127.0.0.1:8001/api/v1';
  const suffix = randomUUID().slice(0, 8).toUpperCase();
  const symbol = 'SYNTH_' + suffix;
  await page.goto('/');
  await page.getByLabel('Local application token').fill(token);
  await page.getByRole('button', { name: /Open workspace/ }).click();
  await expect(page.getByRole('heading', { name: 'Data workbench' })).toBeVisible();
  await page.getByRole('button', { name: 'Instruments & watchlists' }).click();
  await page.getByLabel('Symbol', { exact: true }).fill(symbol);
  await page.getByLabel('Display name').fill('SYNTHETIC TEST ONLY ' + suffix);
  await page.getByRole('button', { name: 'Add listing' }).click();
  await expect(page.getByText('Listing created.')).toBeVisible();
  await page.getByLabel('New watchlist name').fill('SYNTHETIC watchlist ' + suffix);
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(page.getByText('Watchlist created.')).toBeVisible();
  await page.getByRole('button', { name: 'Source qualification' }).click();
  await page.getByLabel('Source label').fill('SYNTHETIC source ' + suffix);
  await page.getByLabel('Data classification').selectOption('SYNTHETIC_TEST');
  await page.getByRole('button', { name: 'Register source' }).click();
  await page.getByRole('button', { name: new RegExp('SYNTHETIC source ' + suffix) }).click();
  await page.getByLabel('Qualification status').selectOption('QUALIFIED_FOR_RESEARCH');
  await page.getByLabel('Rights / usage evidence reference').fill('Generated synthetic test only, no market claims');
  await page.getByLabel('Retention and deletion review reference').fill('Disposable automated test database');
  for (const use of ['retrieval', 'storage', 'analysis', 'display']) await page.getByRole('checkbox', { name: use, exact: true }).check();
  await page.getByRole('button', { name: 'Save qualification review' }).click();
  await expect(page.getByRole('button', { name: new RegExp('SYNTHETIC source ' + suffix + '.*QUALIFIED_FOR_RESEARCH') })).toBeVisible();
  const listings = await (await request.get(root + '/instruments?limit=1000', { headers: auth })).json();
  const listing = listings.data.find((i: { symbol: string }) => i.symbol === symbol);
  const sources = await (await request.get(root + '/data-sources', { headers: auth })).json();
  const source = sources.data.find((s: { label: string }) => s.label === 'SYNTHETIC source ' + suffix);
  await page.getByRole('button', { name: 'CSV imports' }).click();
  await page.getByLabel('ETF listing').selectOption(listing.id);
  await page.getByLabel('Data source').selectOption(source.id);
  await page.getByLabel(/Daily CSV file/).setInputFiles({ name: 'synthetic-test.csv', mimeType: 'text/csv',
    buffer: Buffer.from('trading_date,close\n2026-01-01,10.1234567890\n2026-01-02,12\n') });
  await page.getByRole('button', { name: /Validate & import/ }).click();
  await expect(page.getByText('ACCEPTED', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'History & quality' }).click();
  await expect(page.getByText('10.1234567890', { exact: true })).toBeVisible();
  await expect(page.getByText('SYNTHETIC TEST DATA', { exact: true })).toBeVisible();
  await expect(page.getByText('UNASSESSED', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Instruments & watchlists' }).click();
  const watchlists = await (await request.get(root + '/watchlists', { headers: auth })).json();
  const watchlist = watchlists.data.find((w: { name: string }) => w.name === 'SYNTHETIC watchlist ' + suffix);
  await page.getByRole('combobox', { name: 'Watchlist', exact: true }).selectOption(watchlist.id);
  await page.getByLabel('Listing to add').selectOption(listing.id);
  await page.getByRole('button', { name: 'Add to watchlist' }).click();
  await expect(page.locator('.watchlist').filter({ has: page.locator('input[value="SYNTHETIC watchlist ' + suffix + '"]') }).getByText(symbol, { exact: true })).toBeVisible();
  await page.reload();
  await page.getByLabel('Local application token').fill(token);
  await page.getByRole('button', { name: /Open workspace/ }).click();
  await page.getByLabel('ETF listing').selectOption(listing.id);
  await page.getByLabel('Data source').selectOption(source.id);
  await expect(page.getByText('10.1234567890', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => localStorage.length + sessionStorage.length)).toBe(0);
});
